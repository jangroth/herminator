"""Print herminator-state's README: generated intro plus the Overview table.

Usage: overview.py SRC BUNDLED TAG TIME < previous-README
"""
import json
import os
import subprocess
import sys

INTRO = """\
# herminator-state

Hermes' readable runtime state (config, memories, cron jobs, scripts, skills), \
exported hourly from homekube by [herminator](https://github.com/jangroth/herminator). \
A commit happens only when something changed.

This file is generated by the export. Manual edits are overwritten.

## Overview

Newest first. A row is added only when a value other than the date changes.

Skills are counted by origin: **bundled** is identical to the Hermes image's copy, \
**modified** differs from it, **installed** is listed in `skills/.bundled_manifest` \
but absent from the image, and **created** is none of these.
"""

COLUMNS = ["Date (UTC)", "Hermes", "Skills", "Bundled", "Modified", "Installed",
           "Created", "Cron jobs", "Memory files", "Scripts"]


def row_line(cells):
    return "| " + " | ".join(cells) + " |"


HEADER = row_line(COLUMNS)
RULE = row_line(["---"] * len(COLUMNS))


def unlinked(src, rel):
    """True if neither rel nor any of its parents under src is a symlink."""
    p = src
    for part in rel.split("/"):
        p = os.path.join(p, part)
        if os.path.islink(p):
            return False
    return True


def walk_files(root, skip_dot):
    """Regular files under root, as the export would copy them."""
    for dirpath, dirs, files in os.walk(root):
        dirs[:] = [d for d in dirs
                   if d not in (".git", "__pycache__") and not (skip_dot and d.startswith("."))
                   and not os.path.islink(os.path.join(dirpath, d))]
        for f in files:
            path = os.path.join(dirpath, f)
            if skip_dot and f.startswith("."):
                continue
            if f.endswith(".lock") or os.path.islink(path) or not os.path.isfile(path):
                continue
            yield path


def count_files(src, rel):
    return sum(1 for _ in walk_files(os.path.join(src, rel), False)) if unlinked(src, rel) else 0


def skills(src, bundled):
    root = os.path.join(src, "skills")
    counts = {"bundled": 0, "modified": 0, "installed": 0, "created": 0}
    if not unlinked(src, "skills") or not os.path.isdir(root):
        return counts
    manifest = set()
    mpath = os.path.join(root, ".bundled_manifest")
    if os.path.isfile(mpath) and not os.path.islink(mpath):
        with open(mpath, errors="replace") as f:
            manifest = {line.split(":", 1)[0].strip() for line in f if line.strip()}
    for path in walk_files(root, True):
        if os.path.basename(path) != "SKILL.md":
            continue
        skill = os.path.dirname(path)
        rel = os.path.relpath(skill, root)
        image = os.path.join(bundled, rel)
        if os.path.isdir(image):
            same = subprocess.run(
                ["diff", "-rq", "--no-dereference", "-x", "*.lock", "-x", "__pycache__", image, skill],
                stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL).returncode == 0
            counts["bundled" if same else "modified"] += 1
        elif os.path.basename(skill) in manifest:
            counts["installed"] += 1
        else:
            counts["created"] += 1
    return counts


def cron(src):
    rel = "cron/jobs.json"
    path = os.path.join(src, rel)
    if not unlinked(src, rel) or not os.path.isfile(path):
        return 0, 0
    try:
        with open(path) as f:
            jobs = json.load(f).get("jobs", [])
    except (OSError, ValueError, AttributeError):
        return 0, 0
    if isinstance(jobs, dict):
        jobs = list(jobs.values())
    if not isinstance(jobs, list):
        return 0, 0
    return len(jobs), sum(1 for j in jobs if isinstance(j, dict) and j.get("enabled") is True)


def previous_rows(readme):
    """Rows of the previous Overview table, or [] if it's missing or garbled."""
    lines = readme.splitlines()
    try:
        start = lines.index(HEADER)
    except ValueError:
        return []
    if start + 1 >= len(lines) or lines[start + 1] != RULE:
        return []
    rows = []
    for line in lines[start + 2:]:
        if not line.startswith("|"):
            break
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) != len(COLUMNS):
            return []
        rows.append(cells)
    return rows


def main():
    src, bundled, tag, time = sys.argv[1:5]
    s = skills(src, bundled)
    jobs, enabled = cron(src)
    values = [tag, str(sum(s.values())), str(s["bundled"]), str(s["modified"]),
              str(s["installed"]), str(s["created"]), f"{jobs} ({enabled} enabled)",
              str(count_files(src, "memories")), str(count_files(src, "scripts"))]
    rows = previous_rows(sys.stdin.buffer.read().decode("utf-8", "replace"))
    if not rows or rows[0][1:] != values:
        rows.insert(0, [time.replace("T", " ")[:16]] + values)
    sys.stdout.write(INTRO + "\n" + "\n".join([HEADER, RULE] + [row_line(r) for r in rows]) + "\n")


if __name__ == "__main__":
    main()
